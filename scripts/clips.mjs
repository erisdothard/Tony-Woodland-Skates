/* Tony's skate clips from his Instagram (@ynotwoodland), picked by Eris 2026-10-21. Sources are in
   assets-src/instagram/videos/ (git-ignored), listed in order in scripts/clips.json. Each clip is
   encoded at its own native size (never enlarged), keeps its sound for when a viewer unmutes, and gets
   a poster. Writes public/clips/ and src/content/clips.ts. Versioned names (-v1). Needs ffmpeg.
     node scripts/clips.mjs                                                                     */
import { execFileSync } from 'node:child_process';
import { existsSync, statSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'public/clips');
await mkdir(out, { recursive: true });
const list = JSON.parse(await readFile(path.join(root, 'scripts/clips.json'), 'utf8'));
const run = (args) => execFileSync('ffmpeg', ['-v', 'error', '-y', ...args], { stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 64 * 1024 * 1024 });
const probe = (f) => JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height:format=duration', '-of', 'json', f]).toString());

const clips = [];
for (const c of list) {
  const src = path.join(root, 'assets-src', c.file);
  if (!existsSync(src)) throw new Error(`Missing ${c.file}. Pull it from Instagram first.`);
  const mp4 = `${c.key}-v1.mp4`, jpg = `${c.key}-v1.jpg`;
  if (!existsSync(path.join(out, mp4))) {
    run(['-i', src, '-c:v', 'libx264', '-preset', 'slow', '-crf', '28', '-maxrate', '1200k', '-bufsize', '2400k', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-c:a', 'aac', '-b:a', '96k', '-ac', '2', path.join(out, mp4)]);
  }
  const info = probe(path.join(out, mp4));
  const { width, height } = info.streams[0];
  const duration = Math.round(Number(info.format.duration));
  if (!existsSync(path.join(out, jpg))) {
    const png = run(['-ss', String(Math.min(1, duration / 3)), '-i', src, '-frames:v', '1', '-f', 'image2pipe', '-c:v', 'png', '-']);
    await sharp(png).jpeg({ quality: 80, mozjpeg: true }).toFile(path.join(out, jpg));
  }
  const blur = await sharp(path.join(out, jpg)).resize(16).jpeg({ quality: 50 }).toBuffer();
  clips.push({ key: c.key, alt: c.alt, ig: c.ig, src: `/clips/${mp4}`, poster: `/clips/${jpg}`, width, height, duration, blur: `data:image/jpeg;base64,${blur.toString('base64')}` });
  console.log(mp4.padEnd(30), `${width}x${height}`, `${duration}s`, `${(statSync(path.join(out, mp4)).size / 1048576).toFixed(1)} MB`);
}

const ts = `// Generated by scripts/clips.mjs from scripts/clips.json. Do not edit by hand.
export type Clip = {
  key: string;
  alt: string;
  /** The Instagram post it came from. */
  ig: string;
  src: string;
  poster: string;
  width: number;
  height: number;
  duration: number;
  blur: string;
};

export const clips = ${JSON.stringify(clips, null, 2)} as const satisfies readonly Clip[];
`;
await writeFile(path.join(root, 'src/content/clips.ts'), ts);
console.log(`wrote ${clips.length} clips`);
