/* Moments: short silent "living stills" cut from Rollerblade's films of Tony, at native size.
   Rule (Eris, 2026-10-21): no soft media. No frame grabs of a moving skater as photos, and no clip
   shown larger than its source pixels.
   Sources in assets-src/ (git-ignored), pulled by scripts/fetch-edits.sh and yt-dlp:
     edits/1j8R7Y7CJHs.mp4         Rockit (Rollerblade, 2025, Zach Leavell), 1080p at 60 fps
     edits/YLcKPQl-tbo.mp4         My Escape: Tony's World (Rollerblade, 2021, Richard Williams), 24 fps
     clips/ig-reel-DIjUVA9qpY3.mp4 Rollerblade's Instagram teaser for Rockit (a different cut), 720p
   Writes public/moments/ and src/content/moments.ts. Names are versioned (-v1): never overwrite media
   in place. Needs ffmpeg on PATH and sharp (a project dependency).
     node scripts/moments.mjs                                                                   */
import { execFileSync } from 'node:child_process';
import { existsSync, statSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const src = (f) => path.join(root, 'assets-src', f);
const out = path.join(root, 'public/moments');
await mkdir(out, { recursive: true });

const ROCKIT = 'edits/1j8R7Y7CJHs.mp4';
const CREDIT = 'Rollerblade';
const H264 = ['-c:v', 'libx264', '-preset', 'slow', '-g', '60', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an'];

/* Clips. `speed` below 1 slows a 60 fps source to a smooth 30 fps; `focus` is the CSS object-position
   that keeps Tony in frame when the 16:9 clip is cropped to a portrait box. */
const CLIPS = [
  {
    key: 'tony-smile', file: ROCKIT, from: 70.4, to: 72.9, speed: 0.5, poster: 72.1, focus: '52% 30%',
    alt: 'Tony rolls up to a garage door, turns to the camera with a wide smile and opens his arms.',
  },
];


const ffmpeg = (args) => execFileSync('ffmpeg', ['-v', 'error', '-y', ...args], { stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 64 * 1024 * 1024 });
const need = (file) => {
  if (!existsSync(src(file))) throw new Error(`Missing ${path.join('assets-src', file)}. Pull it first (see the header of this script).`);
};
const kb = (f) => `${(statSync(f).size / 1024).toFixed(0)} KB`;

async function still(file, at, name, longEdge, crop) {
  const png = ffmpeg(['-ss', String(at), '-i', src(file), '-frames:v', '1', ...(crop ? ['-vf', crop] : []), '-f', 'image2pipe', '-c:v', 'png', '-']);
  const img = sharp(png).resize({ width: longEdge, height: longEdge, fit: 'inside', withoutEnlargement: true });
  const data = await img.jpeg({ quality: 82, mozjpeg: true }).toBuffer();
  await writeFile(path.join(out, name), data);
  const { width, height } = await sharp(data).metadata();
  const blur = await sharp(data).resize(16).jpeg({ quality: 50 }).toBuffer();
  return { width, height, blur: `data:image/jpeg;base64,${blur.toString('base64')}` };
}

const clips = [];
for (const c of CLIPS) {
  need(c.file);
  const v = 'v2';
  const mp4 = `${c.key}-${v}.mp4`;
  // Native size, never scaled: the rule is no soft media (CLAUDE.md).
  const size = c.crop ?? 'null';
  const vf = `trim=${c.from}:${c.to},setpts=${(1 / c.speed).toFixed(3)}*(PTS-STARTPTS),fps=30,hqdn3d=1:1:2:2,${size}`;
  ffmpeg(['-i', src(c.file), '-vf', vf, ...H264, '-crf', '21', path.join(out, mp4)]);
  const poster = await still(c.file, c.poster, `${c.key}-${v}.jpg`, 1920, c.crop);
  clips.push({ key: c.key, alt: c.alt, credit: CREDIT, focus: c.focus, src: `/moments/${mp4}`, poster: `/moments/${c.key}-${v}.jpg`, ...poster });
  console.log(mp4.padEnd(24), kb(path.join(out, mp4)));
}

/* Poster for the edits room's My Escape player: one photo of Tony skating, Eris's pick park-air, cropped
   to the player's 16:9 from the top so his raised hand stays in. Reads public/photos/ (scripts/photos.mjs). */
{
  const src = path.join(root, 'public/photos/park-air.jpg');
  const { width, height } = await sharp(src).metadata();
  const h = Math.round((width * 9) / 16);
  const name = 'escape-poster-v3.jpg';
  await sharp(src).extract({ left: 0, top: Math.min(30, height - h), width, height: h }).jpeg({ quality: 84, mozjpeg: true }).toFile(path.join(out, name));
  console.log(name.padEnd(24), kb(path.join(out, name)));
}

const ts = `// Generated by scripts/moments.mjs. Do not edit by hand.
export type Moment = {
  key: string;
  alt: string;
  credit: string;
  /** CSS object-position that keeps Tony in frame when the clip is cropped. */
  focus: string;
  src: string;
  poster: string;
  width: number;
  height: number;
  blur: string;
};

const clips = ${JSON.stringify(clips, null, 2)} as const satisfies readonly Moment[];

export type MomentKey = (typeof clips)[number]['key'];
export const moment = (key: MomentKey): Moment => clips.find((m) => m.key === key)!;
`;
await writeFile(path.join(root, 'src/content/moments.ts'), ts);
console.log('wrote src/content/moments.ts');
