/* Pull Tony's photos from the "Operation Tony" Drive folder (link-shared), make web masters, and
   write src/content/photos.ts. Originals stay in .cache/drive and are never committed.

     node scripts/photos.mjs            # process everything in scripts/photos.json
     DRIVE_CACHE=/path node scripts/photos.mjs                                                */
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import heicConvert from 'heic-convert';

const root = path.resolve(import.meta.dirname, '..');
const cache = process.env.DRIVE_CACHE ?? path.join(root, '.cache/drive');
const out = path.join(root, 'public/photos');
const LONG_EDGE = 2000;

const manifest = JSON.parse(await readFile(path.join(root, 'scripts/photos.json'), 'utf8'));
await mkdir(cache, { recursive: true });
await mkdir(out, { recursive: true });

const exists = (p) => access(p).then(() => true, () => false);

async function original(id) {
  const file = path.join(cache, id);
  if (!(await exists(file))) {
    const url = `https://drive.usercontent.google.com/download?id=${id}&export=download&confirm=t`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Drive ${id}: HTTP ${res.status}`);
    await writeFile(file, Buffer.from(await res.arrayBuffer()));
  }
  let buf = await readFile(file);
  // HEIC/HEIF ("ftypheic", "ftypmif1"...) goes through heic-convert; sharp's prebuilt libheif has no HEVC.
  const brand = buf.subarray(4, 12).toString('latin1');
  if (/^ftyp(heic|heix|hevc|mif1|msf1)/.test(brand)) {
    buf = Buffer.from(await heicConvert({ buffer: buf, format: 'JPEG', quality: 0.95 }));
  }
  return buf;
}

const entries = [];
for (const p of manifest) {
  const src = await original(p.id);
  const img = sharp(src).rotate().resize({ width: LONG_EDGE, height: LONG_EDGE, fit: 'inside', withoutEnlargement: true });
  const { data, info } = await img.jpeg({ quality: 80, mozjpeg: true }).toBuffer({ resolveWithObject: true });
  await writeFile(path.join(out, `${p.key}.jpg`), data);
  const blur = await sharp(data).resize(16).jpeg({ quality: 50 }).toBuffer();
  entries.push({
    key: p.key, set: p.set, alt: p.alt, credit: p.credit ?? null,
    src: `/photos/${p.key}.jpg`, width: info.width, height: info.height,
    blur: `data:image/jpeg;base64,${blur.toString('base64')}`,
  });
  console.log(`${p.key.padEnd(18)} ${info.width}x${info.height} ${(data.length / 1024).toFixed(0)} KB`);
}

const ts = `// Generated by scripts/photos.mjs from scripts/photos.json. Do not edit by hand.
export type Photo = {
  key: string;
  set: 'skate' | 'model';
  alt: string;
  credit: string | null;
  src: string;
  width: number;
  height: number;
  blur: string;
};

export const photos = ${JSON.stringify(entries, null, 2)} as const satisfies readonly Photo[];

export type PhotoKey = (typeof photos)[number]['key'];

export const photo = (key: PhotoKey): Photo => photos.find((p) => p.key === key)!;
export const photoSet = (set: Photo['set']): Photo[] => photos.filter((p) => p.set === set);
`;
await mkdir(path.join(root, 'src/content'), { recursive: true });
await writeFile(path.join(root, 'src/content/photos.ts'), ts);
console.log(`wrote ${entries.length} photos`);
